"""Merchant ledger lookups: data/mock/merchant_ledger.json (mock) and BigQuery (gcp)."""

from __future__ import annotations

import asyncio
import json
import logging
import threading
from datetime import UTC, datetime
from pathlib import Path

from ..paths import mock_data_dir
from .models import LedgerEntry

log = logging.getLogger(__name__)

_COLUMNS = (
    "merchant_id",
    "merchant_vpa",
    "entry_type",
    "txn_id",
    "amount",
    "counterparty_vpa",
    "initiated_at",
    "settled_at",
    "status",
)


class LedgerUnavailable(RuntimeError):
    """The ledger couldn't be read, and no fallback holds this merchant."""


class JsonMerchantLedger:
    """Generated by data/ (an exact subset of trustshield.merchant_ledger)."""

    name = "json"

    def __init__(self, path: Path | None = None):
        data = json.loads(
            (path or mock_data_dir() / "merchant_ledger.json").read_text(encoding="utf-8")
        )
        self._by_key: dict[tuple[str, str], LedgerEntry] = {}
        for row in data.get("entries", []):
            entry = LedgerEntry.model_validate({k: row.get(k) for k in _COLUMNS})
            self._by_key.setdefault((entry.merchant_id, entry.txn_id), entry)
        self._merchants = {merchant_id for merchant_id, _ in self._by_key}

    def covers(self, merchant_id: str) -> bool:
        """The mock holds only a few merchants; "not found" means something only for those."""
        return merchant_id in self._merchants

    async def find(self, merchant_id: str, txn_id: str) -> LedgerEntry | None:
        return self._by_key.get((merchant_id, txn_id))


class BigQueryMerchantLedger:
    """Parameterised lookup on `<project>.<dataset>.merchant_ledger` via the BigQuery REST API.

    Uses google-auth (already installed with google-genai), so no extra dependency. The table is
    clustered by (merchant_id, txn_id); BigQuery bills its 10 MB per-table minimum per lookup,
    inside the free tier for a demo. Read-only: no streaming, no writes.
    """

    name = "bigquery"

    def __init__(self, project: str, dataset: str, location: str, credentials=None):
        self.project, self.dataset, self.location = project, dataset, location
        self._credentials = credentials
        self._session = None
        self._session_lock = threading.Lock()  # find() runs on worker threads

    def _authed_session(self):
        with self._session_lock:
            if self._session is None:
                import google.auth
                from google.auth.transport.requests import AuthorizedSession

                creds = self._credentials
                if creds is None:
                    creds, _ = google.auth.default(
                        scopes=["https://www.googleapis.com/auth/bigquery.readonly"]
                    )
                self._session = AuthorizedSession(creds)
            return self._session

    def request_body(self, merchant_id: str, txn_id: str) -> dict:
        table = f"`{self.project}.{self.dataset}.merchant_ledger`"
        return {
            "query": (
                f"SELECT {', '.join(_COLUMNS)} FROM {table} "
                "WHERE merchant_id = @merchant_id AND txn_id = @txn_id LIMIT 1"
            ),
            "useLegacySql": False,
            "location": self.location,
            "parameterMode": "NAMED",
            "queryParameters": [
                {
                    "name": "merchant_id",
                    "parameterType": {"type": "STRING"},
                    "parameterValue": {"value": merchant_id},
                },
                {
                    "name": "txn_id",
                    "parameterType": {"type": "STRING"},
                    "parameterValue": {"value": txn_id},
                },
            ],
            "formatOptions": {"useInt64Timestamp": True},
            "timeoutMs": 10_000,
        }

    @staticmethod
    def parse_response(body: dict) -> LedgerEntry | None:
        rows = body.get("rows") or []
        if not rows:
            return None
        names = [f["name"] for f in body["schema"]["fields"]]
        values = dict(zip(names, (cell.get("v") for cell in rows[0]["f"]), strict=True))
        for col in ("initiated_at", "settled_at"):  # int64 microseconds since the epoch
            if values.get(col) is not None:
                values[col] = datetime.fromtimestamp(int(values[col]) / 1e6, tz=UTC)
        return LedgerEntry.model_validate(values)

    def _query(self, merchant_id: str, txn_id: str) -> LedgerEntry | None:
        url = f"https://bigquery.googleapis.com/bigquery/v2/projects/{self.project}/queries"
        resp = self._authed_session().post(
            url, json=self.request_body(merchant_id, txn_id), timeout=(5, 15)
        )
        resp.raise_for_status()
        body = resp.json()
        if not body.get("jobComplete", True):
            raise TimeoutError("BigQuery ledger lookup did not finish in time")
        return self.parse_response(body)

    async def find(self, merchant_id: str, txn_id: str) -> LedgerEntry | None:
        return await asyncio.to_thread(self._query, merchant_id, txn_id)


class FallbackLedger:
    """Try the primary ledger. On an error (not on "not found") use the fallback, but only for a
    merchant the fallback actually holds; otherwise raise LedgerUnavailable rather than report a
    real payment as missing."""

    def __init__(self, primary, fallback):
        self.primary, self.fallback = primary, fallback
        self.name = f"{primary.name}->{fallback.name}"

    async def find(self, merchant_id: str, txn_id: str) -> LedgerEntry | None:
        try:
            return await self.primary.find(merchant_id, txn_id)
        except Exception as exc:  # a lookup error must not fail the merchant check
            log.warning("%s ledger lookup failed: %s", self.primary.name, str(exc)[:300])
            if getattr(self.fallback, "covers", lambda _merchant_id: True)(merchant_id):
                return await self.fallback.find(merchant_id, txn_id)
            raise LedgerUnavailable(f"{self.primary.name} ledger failed for {merchant_id}") from exc
