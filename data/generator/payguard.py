"""PayGuard mock data for the agents: merchant_ledger.json and screenshots.json.

merchant_ledger.json  every ledger entry of 4 merchants (incl. the demo merchant MER-DEMO-0042)
                      for the last LEDGER_DAYS, copied unchanged from the merchant_ledger
                      table, so mock and BigQuery modes give the same answers for them.
screenshots.json      what OCR / Gemini vision "reads" off 30 synthetic payment screenshots,
                      keyed by URI: amount, txn_id, vpa, timestamp, tamper_hints, plus when the
                      screenshot was shown (shown_at). `_case` holds the labels the tests use;
                      the extractor ignores it.

Uses its own random stream, so adding cases never changes the main dataset.
"""

from __future__ import annotations

import json
import random
from datetime import datetime, timedelta

import pandas as pd

from . import config as C
from .pipeline import Dataset

LEDGER_DAYS = 30
EXTRA_MERCHANTS = 2
URI_PREFIX = "gs://trustshield-demo-uploads/synthetic"

#: Demo 3, exactly as shared/contracts/fixtures/demo3_fake_screenshot_12k.json tells it.
DEMO3_URI = "gs://trustshield-demo-uploads/demo3/payment_screenshot_12000.png"
DEMO3 = {
    "amount": 12000,
    "txn_id": "428913570012",
    "vpa": "mer.demo0042@synthbank",
    "timestamp": "2026-10-13T14:22:00+05:30",
    "tamper_hints": ["font_mismatch"],
    "shown_at": "2026-10-13T14:19:00+05:30",  # the timestamp is 3 minutes in the future
    "_case": {
        "merchant_id": "MER-DEMO-0042",
        "claimed_amount": 12000,
        "claimed_transaction_id": "428913570012",
        "kind": "demo3_fake_future_timestamp",
        "is_fake": True,
        "expected_status": "suspicious",
    },
}

# kind -> (count, is_fake, expected_status)
CASES = {
    "genuine_settled": (8, False, "verified"),
    "genuine_pending": (3, False, "pending"),
    "fake_tampered": (5, True, "suspicious"),  # + demo 3 = 6
    "fake_clean": (4, True, "not_found_in_ledger"),
    "edited_amount": (4, True, "inconsistent"),
    "edited_vpa": (2, True, "inconsistent"),
    "reused_old_screenshot": (3, True, "inconsistent"),
}
TAMPER_HINTS = ("font_mismatch", "edited_region", "misaligned_text", "unusual_layout")


def _iso(ts) -> str:
    return pd.Timestamp(ts).tz_convert(C.IST).isoformat()


def _ledger_subset(ds: Dataset, rng: random.Random) -> pd.DataFrame:
    ledger = ds["merchant_ledger"]
    demo_ids = [m[0] for m in C.DEMO_MERCHANTS]
    others = sorted(set(ledger["merchant_id"]) - set(demo_ids))
    chosen = demo_ids + rng.sample(others, EXTRA_MERCHANTS)
    since = pd.Timestamp(C.AS_OF - timedelta(days=LEDGER_DAYS))
    sub = ledger[ledger["merchant_id"].isin(chosen) & (ledger["initiated_at"] >= since)]
    return sub.sort_values(["merchant_id", "initiated_at", "txn_id"]).reset_index(drop=True)


def ledger_json(sub: pd.DataFrame, seed: int) -> dict:
    cols = [
        "merchant_id",
        "merchant_vpa",
        "entry_type",
        "txn_id",
        "amount",
        "counterparty_vpa",
        "initiated_at",
        "settled_at",
        "status",
        "refund_of_txn_id",
    ]
    entries = []
    for row in sub[cols].itertuples(index=False):
        entry = row._asdict()
        entry["initiated_at"] = _iso(entry["initiated_at"])
        entry["settled_at"] = None if pd.isna(entry["settled_at"]) else _iso(entry["settled_at"])
        # pandas reads a missing string as NaN, which is not valid JSON.
        entry["refund_of_txn_id"] = (
            None if pd.isna(entry["refund_of_txn_id"]) else entry["refund_of_txn_id"]
        )
        entries.append(entry)
    return {
        "_comment": (
            "Mock merchant ledger for PayGuard (TRUSTSHIELD_MODE=mock). SYNTHETIC. Generated by "
            f"data/ (python -m generator --seed {seed}): the last {LEDGER_DAYS} days of "
            f"{sub['merchant_id'].nunique()} merchants, identical to their rows in BigQuery "
            "trustshield.merchant_ledger. Do not edit by hand."
        ),
        "schema_version": 1,
        "entries": entries,
    }


def _shot(shows: dict, shown_at: datetime, hints=(), **case) -> dict:
    return {
        "amount": shows["amount"],
        "txn_id": shows["txn_id"],
        "vpa": shows["vpa"],
        # Receipts show the time to the minute.
        "timestamp": _iso(pd.Timestamp(shows["timestamp"]).floor("min")),
        "tamper_hints": list(hints),
        "shown_at": _iso(shown_at),
        "_case": case,
    }


def screenshots_json(ds: Dataset, sub: pd.DataFrame, rng: random.Random, seed: int) -> dict:
    used_ids = set(ds["merchant_ledger"]["txn_id"]) | set(ds["transactions"]["txn_id"])
    used_ids |= C.RESERVED_TXN_IDS
    as_of = pd.Timestamp(C.AS_OF)

    def fresh_txn_id() -> str:
        while True:
            value = str(rng.randrange(10**11, 10**12))
            if value not in used_ids:
                used_ids.add(value)
                return value

    credits = sub[sub["entry_type"] == "credit"]
    settled = credits[credits["status"] == "settled"]
    recent_settled = settled[settled["initiated_at"] >= as_of - timedelta(days=1)]
    old_settled = settled[settled["initiated_at"] <= as_of - timedelta(days=3)]
    pending = credits[credits["status"] == "pending"]
    merchants = sorted(sub["merchant_id"].unique())
    vpa_of = dict(zip(sub["merchant_id"], sub["merchant_vpa"], strict=False))

    def pick(df: pd.DataFrame, n: int) -> list:
        rows = list(df.itertuples(index=False))
        return rng.sample(rows, n)

    def case(kind, row_merchant, claimed_amount, claimed_txn):
        _, is_fake, expected = CASES[kind]
        return {
            "merchant_id": row_merchant,
            "claimed_amount": claimed_amount,
            "claimed_transaction_id": claimed_txn,
            "kind": kind,
            "is_fake": is_fake,
            "expected_status": expected,
        }

    def like(amount, txn_id, vpa, ts):
        """What the screenshot shows."""
        return {"amount": amount, "txn_id": txn_id, "vpa": vpa, "timestamp": ts}

    shots: dict[str, dict] = {DEMO3_URI: DEMO3}
    n = 0

    def add(record: dict) -> None:
        nonlocal n
        n += 1
        shots[f"{URI_PREFIX}/screenshot_{n:03d}.png"] = record

    def genuine(row, kind):
        shows = like(row.amount, row.txn_id, row.merchant_vpa, row.initiated_at)
        shown = row.initiated_at + timedelta(minutes=rng.uniform(1, 6))
        return _shot(shows, shown, (), **case(kind, row.merchant_id, row.amount, row.txn_id))

    # One draw for every case built on a real recent credit, so no two screenshots share a txn.
    n_genuine, n_amount, n_vpa = (
        CASES[k][0] for k in ("genuine_settled", "edited_amount", "edited_vpa")
    )
    real = pick(recent_settled, n_genuine + n_amount + n_vpa)
    genuine_rows = real[:n_genuine]
    amount_rows = real[n_genuine : n_genuine + n_amount]
    vpa_rows = real[n_genuine + n_amount :]

    for row in genuine_rows:
        add(genuine(row, "genuine_settled"))
    for row in pick(pending, CASES["genuine_pending"][0]):
        add(genuine(row, "genuine_pending"))

    for i in range(CASES["fake_tampered"][0]):
        merchant = rng.choice(merchants)
        shown = as_of - timedelta(hours=rng.uniform(1, 72))
        amount = float(rng.choice([2_500, 4_999, 7_500, 12_000, 18_000, 25_000]))
        if i % 2 == 0:  # timestamp from the future, plus one visual hint
            ts = shown + timedelta(minutes=rng.randint(2, 15))
            hints = [rng.choice(TAMPER_HINTS)]
        else:  # plausible time, but two visual hints
            ts = shown - timedelta(minutes=rng.randint(1, 5))
            hints = rng.sample(TAMPER_HINTS, 2)
        txn = fresh_txn_id()
        shows = like(amount, txn, vpa_of[merchant], ts)
        add(_shot(shows, shown, hints, **case("fake_tampered", merchant, amount, txn)))

    for _ in range(CASES["fake_clean"][0]):
        merchant = rng.choice(merchants)
        shown = as_of - timedelta(hours=rng.uniform(1, 72))
        amount = float(rng.randrange(300, 9_000, 50))
        txn = fresh_txn_id()
        ts = shown - timedelta(minutes=rng.randint(1, 4))
        shows = like(amount, txn, vpa_of[merchant], ts)
        add(_shot(shows, shown, (), **case("fake_clean", merchant, amount, txn)))

    for i, row in enumerate(amount_rows):
        edited = float(round(row.amount * rng.choice([10, 5, 3]) + rng.choice([0, 500])))
        shows = like(edited, row.txn_id, row.merchant_vpa, row.initiated_at)
        shown = row.initiated_at + timedelta(minutes=rng.uniform(1, 6))
        hints = ["font_mismatch"] if i % 2 == 0 else []
        labels = case("edited_amount", row.merchant_id, edited, row.txn_id)
        add(_shot(shows, shown, hints, **labels))

    for row in vpa_rows:
        other = rng.choice([m for m in merchants if m != row.merchant_id])
        shows = like(row.amount, row.txn_id, vpa_of[other], row.initiated_at)
        shown = row.initiated_at + timedelta(minutes=rng.uniform(1, 6))
        labels = case("edited_vpa", row.merchant_id, row.amount, row.txn_id)
        add(_shot(shows, shown, (), **labels))

    for row in pick(old_settled, CASES["reused_old_screenshot"][0]):
        shows = like(row.amount, row.txn_id, row.merchant_vpa, row.initiated_at)
        shown = as_of - timedelta(minutes=rng.uniform(5, 120))  # shown again today
        labels = case("reused_old_screenshot", row.merchant_id, row.amount, row.txn_id)
        add(_shot(shows, shown, (), **labels))

    return {
        "_comment": (
            "Mock screenshot extraction for PayGuard (TRUSTSHIELD_MODE=mock). SYNTHETIC. "
            f"Generated by data/ (python -m generator --seed {seed}). Keys are screenshot URIs; "
            "shown_at is when the screenshot was shown to the merchant; _case holds test labels "
            "and is not used by the extractor. Do not edit by hand."
        ),
        "schema_version": 1,
        "screenshots": shots,
    }


def build_payguard_mocks(ds: Dataset) -> tuple[dict, dict]:
    rng = random.Random(f"payguard-{ds.seed}")
    sub = _ledger_subset(ds, rng)
    return ledger_json(sub, ds.seed), screenshots_json(ds, sub, rng, ds.seed)


def dumps_ledger(ledger: dict) -> str:
    """One ledger entry per line so diffs stay readable."""
    lines = [f"    {json.dumps(e, ensure_ascii=False, allow_nan=False)}" for e in ledger["entries"]]
    return (
        "{\n"
        f'  "_comment": {json.dumps(ledger["_comment"], ensure_ascii=False)},\n'
        f'  "schema_version": {ledger["schema_version"]},\n'
        '  "entries": [\n' + ",\n".join(lines) + "\n  ]\n}\n"
    )


def dumps_screenshots(shots: dict) -> str:
    return json.dumps(shots, indent=2, ensure_ascii=False, allow_nan=False) + "\n"
